"""Coverage: unsupported and partial outcomes never become FULL."""

from conftest import make_zip

from app import contracts, policy as policy_module, workspace as workspace_module
from app.service import ServiceConfig
from app.stages import RunContext, _stage_extraction, Pipeline

JS = b"function alpha() { return 1; }\nmodule.exports = { alpha };\n"
TSX = (b"export function Widget({ title }: { title: string }) { return <h1>{title}</h1>; }\n")
PY = b"def beta():\n    return 2\n"
JAVA = b"public class Gamma { public int get() { return 3; } }\n"
CS = b"public class Delta { public int Get() { return 4; } }\n"


def _extract(entries, tmp_path):
    from conftest import make_metadata
    archive = make_zip(entries)
    metadata = make_metadata(archive)
    validated = contracts.validate_metadata(metadata)
    root = tmp_path / "ws"
    root.mkdir()
    space = workspace_module.Workspace(root, validated.run_id)
    config = ServiceConfig(secret="x" * 32, workspace_root=root)
    ctx = RunContext(metadata=validated, archive=archive, workspace=space,
                     config=config, policy=policy_module.current_policy())
    pipe = Pipeline(context=ctx)
    pipe.inventory = __import__("app.archive_safety", fromlist=["inspect_zip"]).inspect_zip(archive)
    _stage_extraction(pipe)
    space.cleanup()
    return pipe


def test_five_language_groups_extract(tmp_path):
    pipe = _extract({"a.js": JS, "b.ts": JS, "c.tsx": TSX, "d.py": PY,
                     "e.java": JAVA, "f.cs": CS}, tmp_path)
    assert not [s for s in pipe.stages if s.outcome == "FAILED"]
    assert len(pipe.analyzed) == 6
    dialects = {f.dialect for f in pipe.analyzed}
    assert {"javascript", "typescript", "tsx", "python", "java", "csharp"} <= dialects


def test_unsupported_and_excluded_become_omissions_not_full(tmp_path):
    from app.stages import _coverage_level
    pipe = _extract({
        "a.js": JS,
        "notes.exe": b"MZ-binary",
        "bundle.zip": make_zip({"inner.js": JS}),
        "vendor/lib.js": JS,
        "gen.js": b"// GENERATED by tool\n" + JS,
    }, tmp_path)
    assert not [s for s in pipe.stages if s.outcome == "FAILED"]
    assert len(pipe.analyzed) == 1
    reasons = {o["reason"] for o in pipe.omissions}
    assert {"UNSUPPORTED_EXTENSION", "NESTED_ARCHIVE", "VENDOR_EXCLUDED",
            "GENERATED_EXCLUDED"} <= reasons
    assert _coverage_level(pipe) == "PARTIAL"


def test_fully_unsupported_inventory_is_not_full(tmp_path):
    from app.stages import _coverage_level
    pipe = _extract({"notes.txt": b"plain text", "run.exe": b"MZ"}, tmp_path)
    assert len(pipe.analyzed) == 0
    assert _coverage_level(pipe) == "UNSUPPORTED"


def test_binary_supported_file_is_mandatory_failure(tmp_path):
    pipe = _extract({"evil.js": b"\x00\x01\x02binary"}, tmp_path)
    failed = [s for s in pipe.stages if s.outcome == "FAILED"]
    assert failed and failed[0].error_code == "EXTRACTION_FAILED"
