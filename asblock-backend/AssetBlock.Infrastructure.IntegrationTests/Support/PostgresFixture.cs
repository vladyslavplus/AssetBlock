using System.Diagnostics.CodeAnalysis;
using AssetBlock.Infrastructure.Persistence;
using Microsoft.EntityFrameworkCore;
using Npgsql;
using Testcontainers.PostgreSql;

namespace AssetBlock.Infrastructure.IntegrationTests.Support;

/// <summary>
/// Shared PostgreSQL instance for infrastructure store tests. A loopback-only task database can
/// replace Testcontainers when Docker is unavailable; each fixture owns a separate database.
/// </summary>
public sealed class PostgresFixture : IAsyncLifetime
{
    private static readonly TimeSpan _startTimeout = TimeSpan.FromMinutes(2);

    private PostgreSqlContainer? _postgres;
    private string? _connectionString;
    private NpgsqlConnectionStringBuilder? _externalServer;
    private string? _externalDatabaseName;

    private string ConnectionString => _connectionString
        ?? throw new InvalidOperationException("PostgreSQL fixture has not been initialized.");

    [SuppressMessage("Security", "CA2100:Review SQL queries for security vulnerabilities", Justification = "Database name is generated by this fixture and quoted with NpgsqlCommandBuilder.")]
    public async Task InitializeAsync()
    {
        var externalConnectionString = Environment.GetEnvironmentVariable("ASBLOCK_TEST_POSTGRES");
        if (string.IsNullOrWhiteSpace(externalConnectionString))
        {
            _postgres = new PostgreSqlBuilder("pgvector/pgvector:0.8.6-pg16-bookworm@sha256:ccc6e83d6e35e931dc7c5def2022729d5a6c370318d099181995567ff1fb4d6b").Build();
            using var cts = new CancellationTokenSource(_startTimeout);
            try
            {
                await _postgres.StartAsync(cts.Token);
            }
            catch (OperationCanceledException) when (!cts.IsCancellationRequested)
            {
                throw;
            }
            catch (OperationCanceledException)
            {
                throw new TimeoutException(
                    $"PostgreSQL Testcontainers failed to start within {_startTimeout.TotalSeconds:0}s. " +
                    "Check Docker Desktop is running and not wedged (restart if containers stay in Created).");
            }

            _connectionString = _postgres.GetConnectionString();
            return;
        }

        var supplied = new NpgsqlConnectionStringBuilder(externalConnectionString);
        if (supplied.Host is not ("127.0.0.1" or "::1" or "localhost"))
        {
            throw new InvalidOperationException("ASBLOCK_TEST_POSTGRES must target loopback.");
        }

        _externalServer = new NpgsqlConnectionStringBuilder(supplied.ConnectionString)
        {
            Database = "postgres"
        };
        _externalDatabaseName = $"asblock_r16_test_{Guid.NewGuid():N}";
        await using NpgsqlConnection admin = new(_externalServer.ConnectionString);
        await admin.OpenAsync();
        await using (NpgsqlCommand createDatabase = admin.CreateCommand())
        {
            createDatabase.CommandText = $"CREATE DATABASE {new NpgsqlCommandBuilder().QuoteIdentifier(_externalDatabaseName)}";
            await createDatabase.ExecuteNonQueryAsync();
        }

        _connectionString = new NpgsqlConnectionStringBuilder(supplied.ConnectionString)
        {
            Database = _externalDatabaseName
        }.ConnectionString;
    }

    [SuppressMessage("Security", "CA2100:Review SQL queries for security vulnerabilities", Justification = "Database name is generated by this fixture and quoted with NpgsqlCommandBuilder.")]
    public async Task DisposeAsync()
    {
        if (_connectionString is not null)
        {
            await using var poolKey = new NpgsqlConnection(_connectionString);
            NpgsqlConnection.ClearPool(poolKey);
        }

        if (_externalDatabaseName is not null && _externalServer is not null)
        {
            await using NpgsqlConnection admin = new(_externalServer.ConnectionString);
            await admin.OpenAsync();
            await using NpgsqlCommand dropDatabase = admin.CreateCommand();
            dropDatabase.CommandText = $"DROP DATABASE IF EXISTS {new NpgsqlCommandBuilder().QuoteIdentifier(_externalDatabaseName)} WITH (FORCE)";
            await dropDatabase.ExecuteNonQueryAsync();
            return;
        }

        if (_postgres is not null)
        {
            await _postgres.DisposeAsync();
        }
    }

    public ApplicationDbContext CreateDbContext(
        Action<DbContextOptionsBuilder<ApplicationDbContext>>? configure = null)
    {
        DbContextOptionsBuilder<ApplicationDbContext> optionsBuilder = new DbContextOptionsBuilder<ApplicationDbContext>()
            .UseNpgsql(ConnectionString, npgsql => npgsql.UseVector())
            .AddInterceptors(new AssetBlock.Infrastructure.Persistence.Interceptors.AuditTimestampsInterceptor(TimeProvider.System));
        configure?.Invoke(optionsBuilder);
        return new ApplicationDbContext(optionsBuilder.Options);
    }

    /// <summary>
    /// Creates a context against a wiped schema with the full EF migration history applied.
    /// </summary>
    public async Task<ApplicationDbContext> CreateCleanDbContext(
        Action<DbContextOptionsBuilder<ApplicationDbContext>>? configure = null,
        CancellationToken cancellationToken = default)
    {
        await using (ApplicationDbContext setup = CreateDbContext())
        {
            await setup.Database.ExecuteSqlRawAsync(
                """
                DROP SCHEMA IF EXISTS public CASCADE;
                CREATE SCHEMA public;
                CREATE EXTENSION IF NOT EXISTS vector WITH SCHEMA public;
                """,
                cancellationToken);

            await setup.Database.MigrateAsync(cancellationToken);
        }

        return CreateDbContext(configure);
    }
}
