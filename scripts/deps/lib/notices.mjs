import { collectLicenseIds, findException, parseLicenseExpression } from "./policy.mjs";

function packageKey(pkg) {
  return `${pkg.ecosystem}:${pkg.name}@${pkg.version}`;
}

function exceptionKey(exception) {
  return `${exception.ecosystem}:${exception.namePattern ?? exception.name}`;
}

function formatPackageEntry(pkg) {
  const lines = [`- \`${pkg.ecosystem}\` ${pkg.name}@${pkg.version}`];
  if (pkg.author) {
    lines.push(`  - copyright/author: ${pkg.author}`);
  }
  if (pkg.sourceUrl) {
    lines.push(`  - source: ${pkg.sourceUrl}`);
  }
  if (pkg.licenseUrl) {
    lines.push(`  - license-url: ${pkg.licenseUrl}`);
  } else if (pkg.license && /^[A-Za-z0-9.\-+]+$/.test(pkg.license)) {
    lines.push(`  - license-url: https://spdx.org/licenses/${pkg.license}.html`);
  }
  return lines.join("\n");
}

export function buildNoticesMarkdown(packages) {
  const byLicense = new Map();

  for (const pkg of packages) {
    const licenseLabel = pkg.license ?? "UNKNOWN";
    if (!byLicense.has(licenseLabel)) {
      byLicense.set(licenseLabel, []);
    }
    byLicense.get(licenseLabel).push(pkg);
  }

  const licenseKeys = [...byLicense.keys()].sort((a, b) => a.localeCompare(b));
  const lines = [
    "# Third-party notices",
    "",
    "This file is generated by `pnpm deps:generate`. Do not edit by hand.",
    "It lists direct and transitive NuGet and npm dependencies used by AssetBlock,",
    "including root tooling lockfile packages and optional platform packages so the",
    "inventory is OS-independent across repository npm roots.",
    "",
    "Where available, each entry includes author/copyright, source repository/homepage,",
    "and a license URL (SPDX page or package-declared license URL). Metadata is read from",
    "local package.json when present, with the npm registry used as a fallback.",
    "",
  ];

  for (const license of licenseKeys) {
    lines.push(`## ${license}`, "");
    const pkgs = byLicense
      .get(license)
      .slice()
      .sort(
        (a, b) =>
          a.ecosystem.localeCompare(b.ecosystem) ||
          a.name.localeCompare(b.name) ||
          a.version.localeCompare(b.version),
      );

    for (const pkg of pkgs) {
      lines.push(formatPackageEntry(pkg));
    }
    lines.push("");
  }

  return `${lines.join("\n").replace(/\n+$/, "")}\n`;
}

export function evaluatePackages(packages, policy, exceptions) {
  const errors = [];

  for (const pkg of packages) {
    const exception = findException(exceptions, pkg.ecosystem, pkg.name, pkg.version);

    let effectiveLicense = pkg.license;
    if (!effectiveLicense && exception?.license) {
      effectiveLicense = exception.license;
      pkg.license = exception.license;
      pkg.licenseFromException = true;
      if (!pkg.licenseUrl && /^[A-Za-z0-9.\-+]+$/.test(exception.license)) {
        pkg.licenseUrl = `https://spdx.org/licenses/${exception.license}.html`;
      }
    }

    if (!effectiveLicense) {
      errors.push(
        `${packageKey(pkg)}: missing license metadata (add dependency-exceptions.json entry)`,
      );
      continue;
    }

    const ast = parseLicenseExpression(effectiveLicense);
    const ids = [...collectLicenseIds(ast)];
    const allowed = new Set(policy.allowedLicenses);

    const isAllowed = (() => {
      if (!ast) {
        return false;
      }
      const evaluate = (node) => {
        if (node.type === "license") {
          return allowed.has(node.value);
        }
        if (node.type === "or") {
          return evaluate(node.left) || evaluate(node.right);
        }
        if (node.type === "and") {
          return evaluate(node.left) && evaluate(node.right);
        }
        return false;
      };
      return evaluate(ast);
    })();

    if (isAllowed) {
      continue;
    }

    if (!exception) {
      errors.push(
        `${packageKey(pkg)}: license '${effectiveLicense}' is not allowed (ids: ${ids.join(", ")})`,
      );
      continue;
    }

    const exceptionLicense = exception.license;
    if (
      exceptionLicense &&
      normalizeComparable(exceptionLicense) !== normalizeComparable(effectiveLicense)
    ) {
      const exceptedIds = [...collectLicenseIds(parseLicenseExpression(exceptionLicense))];
      const overlap = ids.some((id) => exceptedIds.includes(id)) || ids.includes(exceptionLicense);
      if (!overlap && effectiveLicense !== exceptionLicense) {
        errors.push(
          `${packageKey(pkg)}: exception license '${exceptionLicense}' does not match package license '${effectiveLicense}'`,
        );
      }
    }
  }

  for (const exception of exceptions) {
    const key = exceptionKey(exception);
    const stillPresent = packages.some((pkg) =>
      Boolean(findException([exception], pkg.ecosystem, pkg.name, pkg.version)),
    );
    if (!stillPresent) {
      errors.push(
        `exception ${key} is unused (package no longer present at a listed version); remove or update dependency-exceptions.json`,
      );
    }
  }

  return errors;
}

function normalizeComparable(value) {
  return String(value).trim().toLowerCase();
}

export function filterSevereVulnerabilities(findings, policy) {
  const failSeverities = new Set(
    (policy.failVulnerabilitySeverities ?? ["High", "Critical"]).map((s) =>
      String(s).toLowerCase(),
    ),
  );

  return findings.filter((finding) =>
    failSeverities.has(String(finding.severity ?? "").toLowerCase()),
  );
}
